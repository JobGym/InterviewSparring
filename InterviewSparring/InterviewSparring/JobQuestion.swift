import Foundation


enum JobQuestion {
    case developer
    case designer
    case projectManager
    case researcher
    
    func fetchQuestion() -> [String] {
        switch self {
        case .projectManager:
            return [
                "1. 본 직군으로 지원을 결정하시게 된 계기와, 앞으로 팀네이버에서 어떻게 성장하고 싶은지 작성해 주세요. (최대 1000자 이내) \n*앞으로 팀네이버에서 성취하고 싶은 모습을 구체적으로 그려주시고, 그 목표를 달성하기 위해 어떤 노력을 기울이고자 하는지 포함해 주세요.",
                "2. 가장 열정을 가지고 임했던 프로젝트(목표/과제 등)를 소개해 주시고, 해당 프로젝트의 수행 과정 및 결과에 대해 기재해 주세요. (최대 1000자 이내) \n* 프로젝트를 시작하게 된 계기, 수행 과정에서 마주한 고민과 어려움, 이를 극복했던 과정과 결과, 다수가 함께했던 프로젝트라면 기여도, 이 과정을 통해 느낀 점을 구체적으로 기재해 주세요.",
                "3. 선택하신 모집 부문에 관심을 가지게 된 계기와, 해당 서비스 분야와 관련된 활동 경험에 대해 구체적으로 기재해 주세요.언제 어떤 활동을 하였고, 이 과정을 통해 얻거나 깨달은 바에 대해 설명해 주세요. (최대 1000자 이내) \n(학교 수업, 프로젝트, 대외활동, 글로벌 경험 등)",
                "4. 선택하신 모집 부문과 관련된 해외 서비스 중 올해의 트렌드를 주도할 서비스를 한 가지 선택하여, 기획적 관점에서 해당 서비스가 트렌드를 주도할 것으로 예상되는 요인 및 방식에 대해 서술해 주세요. 또한, 본인이 해당 서비스의 기획자라면, 사용자 혹은 판매자 관점에서 보다 가치 있는 서비스로 어떻게 발전시킬 수 있을지 제안해 주세요. (최대 1000자 이내)"
            ]
            
        case .developer:
            return [
                "1. 본 직군으로 지원을 결정하시게 된 계기와, 앞으로 팀네이버에서 어떻게 성장하고 싶은지 작성해 주세요. (최대 1000자 이내) \n* 앞으로 팀네이버에서 성취하고 싶은 모습을 구체적으로 그려주시고, 그 목표를 달성하기 위해 어떤 노력을 기울이고자 하는지 포함해 주세요.",
                "2. 가장 열정을 가지고 임했던 프로젝트(목표/과제 등)를 소개해 주시고, 해당 프로젝트의 수행 과정 및 결과에 대해 기재해 주세요. (최대 1000자 이내) \n* 지원 부문과 관련된, 어려웠거나 인상 깊었던 문제를 해결한 경험을 중심으로 작성해 주세요.(학교수업, 경진대회, 대외활동 등) \n* 맞닥뜨린 문제를 ‘구체적’으로 기술하고, 본인의 접근 방법과 해결 과정, 그리고 실제 결과를 ‘상세히’ 기술해 주세요. \n* 문제를 잘 해결했다면 그 경험에서 아쉬웠던 점 혹은 더 나은 방법은 없었을지에 대한 고민 과정을 함께 작성해 주세요. \n* 해결하지 못한 경험이더라도 해결을 위해 얼마나 깊이 있게 고민을 했는지 그 과정에 대해 이야기 해 주세요. \n※ 코드로 설명해 주셔도 좋습니다.",
                "3. 다음 중 본인이 가장 자신 있고 희망하는 분야를 한 가지 선택해 주세요. (최대 1000자 이내) \n선택한 분야에 관심을 갖게 된 계기와 자신 있는 이유(그 동안의 노력, 경험, 강점 포함) 등에 대해 구체적으로 설명해 주세요. \n#채용 전형 진행에 참고할게요 #인터뷰 전형에서 구체적인 경험을 질문할 수도 있어요 #잘 어필할 수 있는 분야로 작성해 주세요",
                "4. 본인의 대표적인 개발 경험, 활동을 가장 잘 보여줄 수 있는 프로젝트에 대해 간단한 소개나 설명을 해주세요. (최대 1000자 이내) \n공동 프로젝트였다면 본인의 역할을 명확히 써 주세요. \n* 수강하셨거나 별도로 공부하신 컴퓨터공학 관련 학습/과제/프로젝트 활동을 보여 주셔도 좋습니다."
            ]
            
        case .designer:
            return [
                "1. 본 직군으로 지원을 결정하시게 된 계기와, 앞으로 팀네이버에서 어떻게 성장하고 싶은지 작성해 주세요. (최대 1000자 이내) \n* 앞으로 팀네이버에서 성취하고 싶은 모습을 구체적으로 그려주시고, 그 목표를 달성하기 위해 어떤 노력을 기울이고자 하는지 포함해 주세요.",
                "2. 가장 열정을 가지고 임했던 프로젝트(목표/과제 등)를 소개해 주시고, 해당 프로젝트의 수행 과정 및 결과에 대해 기재해 주세요. (최대 1000자 이내) \n프로젝트를 시작하게 된 계기, 고민의 흐름과 결과 도출 과정, 다수가 함께한 프로젝트라면 기여도,본인만의 디자인 스킬 강점, 이 과정을 통해 느낀 점을 구체적으로 기재해 주세요.",
                "3. 다음 디자인 세부 영역 중, 팀네이버에서 역량을 발휘하고자 하는 영역을 우선순위 별로 작성해 주시고, 그렇게 선택한 이유를 알려주세요. (최대 1000자 이내) \n■ Product Design ■ Experience Insight & Planning ■ Visual Comm.& Brand Design ■ Interactive Design ■ Content Writing \n* 최대 2순위까지 작성 가능하며, 영역 별 상세 설명은 공고문에서 확인하실 수 있습니다. \n* 작성 가이드 : 1) Product Design  2) Visual Comm.& Brand Design / 줄바꿈 / 선택 이유 : ",
                "4. 3번에서 선택한 디자인 세부 영역과 관련된 프로젝트의 포트폴리오를 설명해 주세요. (최대 1000자 이내) \n* 작성 가이드 : 대표 프로젝트 최대 3개까지 작성 가능"
            ]
            
        case .researcher:
            return [
                //explanation 추가
                "사용자에 대한 인사이트를 얻고, 이를 효과적으로 적용한 사례를 알려주세요. ",
                "1. 리서치를 통해 어떤 것을 알아보고 검증하고자 하셨나요?",
                "2. 리서치 설계에 있어 가장 고민했던 점은 무엇인가요?",
                "3. 리서치를 통해 새롭게 발견한 것은 무엇이었으며, 발견한 인사이트를 어떻게 적용했나요?",
                "4. 인사이트가 의미가 있었나요? 그렇게 생각하는 이유는 무엇인가요? \n이 사례를 대표하는 경험을 작성해주세요(선택) \n리서치 과정 혹은 제품의 as-is, to-be를 확인할 수 있는 내용이라면 좋습니다."
            ]
        }
    }
}


